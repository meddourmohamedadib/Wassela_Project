    function getCourseIcon(category) {

        const value =
            String(
                category || ""
            ).toLowerCase();

        if (
            value.includes("artificial") ||
            value.includes("ai")
        ) {
            return "fa-brain";
        }

        if (
            value.includes("program")
        ) {
            return "fa-code";
        }

        if (
            value.includes("math")
        ) {
            return "fa-calculator";
        }

        if (
            value.includes("computer")
        ) {
            return "fa-laptop-code";
        }

        return "fa-book-open";
    }

