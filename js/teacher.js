/* =========================================================
   TRANSLATION HELPER
   ========================================================= */

function t(text) {

    if (!text) {
        return text;
    }

    const cleanText = String(text).trim();

    return (
        languageData[currentLanguage]?.[cleanText] ||
        languageData.en[cleanText] ||
        text
    );
}


/* =========================================================
   SAVE ORIGINAL TEXT
   ========================================================= */

function prepareTranslationNodes() {

    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode: (node) => {

                const parent = node.parentElement;

                if (!parent) {
                    return NodeFilter.FILTER_REJECT;
                }

                const tag = parent.tagName.toLowerCase();

                if (
                    tag === "script" ||
                    tag === "style" ||
                    tag === "noscript"
                ) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (!node.nodeValue.trim()) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    let node;

    while ((node = walker.nextNode())) {

        if (!node.dataset) {
            continue;
        }

        if (!node.__wasslaOriginalText) {
            node.__wasslaOriginalText =
                node.nodeValue;
        }
    }
}


/* =========================================================
   TRANSLATE ALL PAGE TEXT
   ========================================================= */

function translatePageText() {

    prepareTranslationNodes();

    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode: (node) => {

                const parent = node.parentElement;

                if (!parent) {
                    return NodeFilter.FILTER_REJECT;
                }

                const tag = parent.tagName.toLowerCase();

                if (
                    tag === "script" ||
                    tag === "style" ||
                    tag === "noscript"
                ) {
                    return NodeFilter.FILTER_REJECT;
                }

                if (!node.nodeValue.trim()) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const nodes = [];

    let node;

    while ((node = walker.nextNode())) {
        nodes.push(node);
    }

    nodes.forEach((textNode) => {

        if (!textNode.__wasslaOriginalText) {
            textNode.__wasslaOriginalText =
                textNode.nodeValue;
        }

        const original =
            textNode.__wasslaOriginalText;

        const trimmed =
            original.trim();

        if (!trimmed) {
            return;
        }

        const translated =
            t(trimmed);

        if (translated === trimmed) {
            return;
        }

        const start =
            original.indexOf(trimmed);

        const end =
            start + trimmed.length;

        textNode.nodeValue =
            original.substring(0, start) +
            translated +
            original.substring(end);
    });
}


